import slugs from './starter-slugs.json';
import type { ListProblem, ProblemList, ProblemListSection } from './types';

type SeedProblem = [id: string, title: string];
type SeedSection = [id: string, title: string, problems: SeedProblem[]];

const slugById = slugs as Record<string, string>;

function starterProblem(id: string, title: string): ListProblem {
  const slug = slugById[id];
  if (!slug) throw new Error(`Missing LeetCode slug for problem ${id}`);
  return { id, title, url: `https://leetcode.cn/problems/${slug}/` };
}

function starterList(
  id: string,
  title: string,
  sourceId: string,
  sections: SeedSection[],
): ProblemList {
  const mappedSections: ProblemListSection[] = sections.map(([sectionId, sectionTitle, entries]) => ({
    id: sectionId,
    title: sectionTitle,
    problems: entries.map(([problemId, problemTitle]) => starterProblem(problemId, problemTitle)),
  }));

  return {
    id,
    title: `靈神｜${title}`,
    author: '靈茶山艾府',
    sourceUrl: `https://leetcode.cn/discuss/post/${sourceId}/`,
    description: '收錄原題單的入門章節；完整路線請見原始題單。',
    sections: mappedSections,
    initialCompleted: [],
  };
}

